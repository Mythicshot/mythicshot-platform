// node scripts/build-mark.ts: regenerates src/dash/mark.ts from src/dash/mark.png, the
// product's mark (the same file as the front page's). The app serves the mark from that
// module's bytes on both targets, as it serves its stylesheets and scripts from strings:
// no static-files setup on either. test/node-home.test.ts fails when the two differ.
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const PNG = fileURLToPath(new URL("../src/dash/mark.png", import.meta.url));
const MODULE = fileURLToPath(new URL("../src/dash/mark.ts", import.meta.url));

const base64 = readFileSync(PNG).toString("base64");
writeFileSync(
  MODULE,
  `// Generated by scripts/build-mark.ts from src/dash/mark.png, the product's mark: 64 by 64
// pixels, shown at 24 (src/brand.ts). Do not edit: run \`node scripts/build-mark.ts\`.
// test/node-home.test.ts checks it is current.
const BASE64 = ${JSON.stringify(base64)};

/** The mark's PNG bytes, as served on /dash/mark.png. Copy them for each answer. */
export const MARK_PNG: Uint8Array = Uint8Array.from(atob(BASE64), (c) => c.charCodeAt(0));
`,
);
console.log("wrote src/dash/mark.ts");

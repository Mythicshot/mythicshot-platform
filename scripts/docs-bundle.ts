// Builds the two generated modules behind the API documentation page.
//
// The page is served by the app itself on both targets, from strings, exactly as the
// player is (see scripts/player-bundle.ts): the Worker and the container serve the same
// bytes with the same headers, and neither needs a static-files setup.
// - src/docs/viewer-assets.ts carries the reference viewer's script, stylesheet and
//   licence notices, copied unchanged from the pinned swagger-ui-dist package in
//   node_modules. It changes only when that package is upgraded.
// - src/docs/site-assets.ts carries our own page script (src/docs/client/main.ts, bundled
//   with esbuild) and stylesheet, and the API description as JSON and as YAML, both
//   written from openapi() in src/docs/openapi.ts. It changes with the description, the
//   version and every limit the description states.
// Both are committed; test/node-docs-build.test.ts fails when either is stale, and
// scripts/package-cpanel.ts refuses to package a stale one.
import { createHash } from "node:crypto";
import { readFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { build } from "esbuild";
import { stringify } from "yaml";
import { PAGE_BASE_CSS } from "../src/brand-css.ts";
import { openapi } from "../src/docs/openapi.ts";

const ROOT = fileURLToPath(new URL("..", import.meta.url));
/** The viewer's package, as npm installed it. Its install script is never run. */
export const VIEWER_PACKAGE = "swagger-ui-dist";
const VIEWER_DIR = new URL(`../node_modules/${VIEWER_PACKAGE}/`, import.meta.url);
export const VIEWER_MODULE = fileURLToPath(new URL("../src/docs/viewer-assets.ts", import.meta.url));
export const SITE_MODULE = fileURLToPath(new URL("../src/docs/site-assets.ts", import.meta.url));

/** The package's notice files, in the order they are shipped. */
export const VIEWER_NOTICE_FILES = ["NOTICE", "LICENSE", "swagger-ui-bundle.js.LICENSE.txt"] as const;

const digest = (s: string) => createHash("sha256").update(s, "utf8").digest("hex");
const etag = (s: string) => `"${digest(s).slice(0, 32)}"`;
const constant = (name: string, value: string, typed = false) => `export const ${name}${typed ? ": string" : ""} = ${JSON.stringify(value)};`;

/** One file of the viewer's package as text. Refuses bytes that are not UTF-8, so the text served is the file. */
function viewerFile(name: string): string {
  const bytes = readFileSync(new URL(name, VIEWER_DIR));
  const text = new TextDecoder("utf-8", { fatal: true, ignoreBOM: true }).decode(bytes);
  if (!Buffer.from(text, "utf8").equals(bytes)) throw new Error(`${VIEWER_PACKAGE}/${name} does not survive being read as text`);
  return text;
}

/** The version of the viewer's package in node_modules. */
export function viewerVersion(): string {
  const version = (JSON.parse(viewerFile("package.json")) as { version?: unknown }).version;
  if (typeof version !== "string") throw new Error(`${VIEWER_PACKAGE} has no version`);
  return version;
}

/** The licence notices that travel with the viewer: what the package ships, whole, under one heading each. */
export function viewerLicences(): string {
  const rule = "=".repeat(72);
  const parts = [
    `${VIEWER_PACKAGE} ${viewerVersion()}`,
    "",
    "The API reference on the documentation page is shown with Swagger UI, used",
    "under the Apache License 2.0. Its files are served unchanged. Below are the",
    "notice, the licence and the third-party notices its package ships.",
    "",
  ];
  for (const name of VIEWER_NOTICE_FILES) parts.push(rule, `${VIEWER_PACKAGE}/${name}`, rule, "", viewerFile(name).replace(/\r\n/g, "\n").trimEnd(), "");
  return parts.join("\n");
}

/** The text of src/docs/viewer-assets.ts. */
export function viewerModule(): string {
  const js = viewerFile("swagger-ui-bundle.js");
  const css = viewerFile("swagger-ui.css");
  return [
    `// Generated by scripts/build-docs.ts from the ${VIEWER_PACKAGE} package in node_modules.`,
    "// Do not edit: run `npm run build:docs`. test/node-docs-build.test.ts checks it is current.",
    "// The script and the stylesheet are the package's files, byte for byte, with the licence",
    "// comment they carry. The page links the *_PATH addresses, which carry the first 16 hex",
    "// digits of each file's SHA-256.",
    constant("VIEWER_VERSION", viewerVersion()),
    constant("VIEWER_JS", js, true),
    constant("VIEWER_JS_ETAG", etag(js)),
    constant("VIEWER_JS_PATH", `/docs/viewer.${digest(js).slice(0, 16)}.js`),
    constant("VIEWER_CSS", css, true),
    constant("VIEWER_CSS_ETAG", etag(css)),
    constant("VIEWER_CSS_PATH", `/docs/viewer.${digest(css).slice(0, 16)}.css`),
    constant("VIEWER_LICENCES", viewerLicences(), true),
    "",
  ].join("\n");
}

/** Our page script, bundled as the player's is, and our stylesheet after the brand's tokens and font (src/brand-css.ts). */
export async function bundleDocs(): Promise<{ js: string; css: string }> {
  const out = await build({
    absWorkingDir: ROOT,
    entryPoints: ["src/docs/client/main.ts"],
    bundle: true,
    format: "iife",
    target: "es2020",
    platform: "browser",
    charset: "ascii",
    legalComments: "none",
    write: false,
    logLevel: "silent",
  });
  const js = out.outputFiles[0].text;
  const css = PAGE_BASE_CSS + readFileSync(fileURLToPath(new URL("../src/docs/client/docs.css", import.meta.url)), "utf8").replace(/\r\n/g, "\n");
  return { js, css };
}

/** The description as the two files the server hands out. */
export function descriptionFiles(): { json: string; yaml: string } {
  const doc = openapi();
  return { json: JSON.stringify(doc, null, 2) + "\n", yaml: stringify(doc, { lineWidth: 0 }) };
}

/** The text of src/docs/site-assets.ts. */
export async function siteModule(): Promise<string> {
  const { js, css } = await bundleDocs();
  const { json, yaml } = descriptionFiles();
  return [
    "// Generated by scripts/build-docs.ts from src/docs/client/main.ts, src/docs/client/docs.css",
    "// and openapi() in src/docs/openapi.ts.",
    "// Do not edit: run `npm run build:docs`. test/node-docs-build.test.ts checks it is current.",
    constant("DOCS_JS", js, true),
    constant("DOCS_JS_ETAG", etag(js)),
    constant("DOCS_JS_PATH", `/docs/docs.${digest(js).slice(0, 16)}.js`),
    constant("DOCS_CSS", css, true),
    constant("DOCS_CSS_ETAG", etag(css)),
    constant("DOCS_CSS_PATH", `/docs/docs.${digest(css).slice(0, 16)}.css`),
    constant("OPENAPI_JSON", json, true),
    constant("OPENAPI_JSON_ETAG", etag(json)),
    constant("OPENAPI_YAML", yaml, true),
    constant("OPENAPI_YAML_ETAG", etag(yaml)),
    "",
  ].join("\n");
}

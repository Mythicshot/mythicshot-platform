// Builds the player's two files and the generated module that carries them.
//
// The player is served by the app itself on both targets (GET /player.js and
// /player.css), from strings in src/player/assets.ts, so the Worker and the container
// serve the same bytes with the same headers and neither needs a static-files setup or
// a build step at deploy time. That module is generated here from src/player/main.ts
// (bundled with esbuild, the shared rules included) and src/player/player.css, and is
// committed; test/node-player-build.test.ts fails when it is stale.
import { createHash } from "node:crypto";
import { readFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { build } from "esbuild";

const ROOT = fileURLToPath(new URL("..", import.meta.url));
export const ASSETS_MODULE = fileURLToPath(new URL("../src/player/assets.ts", import.meta.url));

export async function bundlePlayer(): Promise<{ js: string; css: string }> {
  const out = await build({
    absWorkingDir: ROOT,
    entryPoints: ["src/player/main.ts"],
    bundle: true,
    format: "iife",
    target: "es2020",
    platform: "browser",
    charset: "ascii",
    legalComments: "none",
    write: false,
    logLevel: "silent",
  });
  const js = out.outputFiles[0].text;
  const css = readFileSync(fileURLToPath(new URL("../src/player/player.css", import.meta.url)), "utf8");
  return { js, css };
}

const digest = (s: string) => createHash("sha256").update(s, "utf8").digest("hex");
const etag = (s: string) => `"${digest(s).slice(0, 32)}"`;

/** The text of src/player/assets.ts. */
export async function assetsModule(): Promise<string> {
  const { js, css } = await bundlePlayer();
  return [
    "// Generated by scripts/build-player.ts from src/player/main.ts and src/player/player.css.",
    "// Do not edit: run `npm run build:player`. test/node-player-build.test.ts checks it is current.",
    "// The pages link the *_PATH addresses, which carry the first 16 hex digits of each file's",
    "// SHA-256, so a page always loads the script and stylesheet built with it.",
    `export const PLAYER_JS: string = ${JSON.stringify(js)};`,
    `export const PLAYER_JS_ETAG = ${JSON.stringify(etag(js))};`,
    `export const PLAYER_JS_PATH = ${JSON.stringify(`/player.${digest(js).slice(0, 16)}.js`)};`,
    `export const PLAYER_CSS: string = ${JSON.stringify(css)};`,
    `export const PLAYER_CSS_ETAG = ${JSON.stringify(etag(css))};`,
    `export const PLAYER_CSS_PATH = ${JSON.stringify(`/player.${digest(css).slice(0, 16)}.css`)};`,
    "",
  ].join("\n");
}

// Builds src/brand-assets.ts, the generated module that carries the brand's files into the
// app: the small mark (the top bar's and the tab icon's), the wordmark (the name beside it,
// drawn by scripts/build-wordmark.py), the tab icon as ICO, and the text font with its licence. The app serves them from this module's strings on both targets,
// as it serves the player's files (scripts/player-bundle.ts): no static-files setup on
// either, the same bytes and headers everywhere.
//
// The files themselves are in src/brand-files/, committed: the marks are the brand's SVG
// files unchanged, favicon.ico is made from them by scripts/build-icons.ts, the wordmark's two
// PNG pictures by scripts/build-wordmark.py, and the font is the published variable TrueType
// file, unchanged but renamed, with its licence (OFL.txt) beside it. The SIL Open Font License 1.1 asks that the licence and the copyright notice
// travel with every copy of a font: the module carries each font's OFL.txt whole next to
// its bytes, and the app serves both.
//
// A font's address names its content (the first 16 hex digits of its SHA-256), so a page
// may keep it for good; test/node-brand-build.test.ts fails when the module is stale.
import { createHash } from "node:crypto";
import { readFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

export const BRAND_MODULE = fileURLToPath(new URL("../src/brand-assets.ts", import.meta.url));
const FILES = new URL("../src/brand-files/", import.meta.url);

/** One file of src/brand-files/ as bytes. */
export const brandFile = (name: string) => readFileSync(new URL(name, FILES));

/** A text file as text, refused unless it is exact UTF-8 with no carriage return. */
function textFile(name: string): string {
  const bytes = brandFile(name);
  const text = new TextDecoder("utf-8", { fatal: true, ignoreBOM: true }).decode(bytes);
  if (!Buffer.from(text, "utf8").equals(bytes) || text.includes("\r")) throw new Error(`src/brand-files/${name} is not plain UTF-8 text with LF line ends`);
  return text;
}

/** A PNG's width and height, from its header. */
function pngSize(png: Uint8Array): [number, number] {
  const view = new DataView(png.buffer, png.byteOffset, png.byteLength);
  if (view.getUint32(0) !== 0x89504e47 || view.getUint32(12) !== 0x49484452) throw new Error("not a PNG");
  return [view.getUint32(16), view.getUint32(20)];
}

const digest = (b: Uint8Array) => createHash("sha256").update(b).digest("hex");
const constant = (name: string, value: string, typed = false) => `export const ${name}${typed ? ": string" : ""} = ${JSON.stringify(value)};`;

/** The font: the file in src/brand-files/fonts/, and the name its address starts with. */
export const FONTS = [
  { id: "MANROPE", name: "manrope", file: "fonts/manrope/Manrope-VariableFont_wght.ttf", licence: "fonts/manrope/OFL.txt" },
] as const;

/** The text of src/brand-assets.ts. */
export function brandModule(): string {
  const lines = [
    "// Generated by scripts/build-brand.ts from the files in src/brand-files/. Do not edit: run",
    "// `npm run build:brand`. test/node-brand-build.test.ts checks it is current. The font is",
    "// SIL Open Font License 1.1: its licence text, with its copyright line, is carried here",
    "// beside it and served beside it (src/brand-routes.ts).",
    "",
    "/** Bytes from base64, made once, on first use, so a start does not pay for files nobody asked for. */",
    "function lazy(base64: string): () => Uint8Array {",
    "  let bytes: Uint8Array | null = null;",
    "  return () => (bytes ??= Uint8Array.from(atob(base64), (c) => c.charCodeAt(0)));",
    "}",
    "",
    "/** The small mark (mythicshot-mark-small.svg), for the top bar and the tab icon: below 48 pixels. */",
    constant("MARK_SMALL_SVG", textFile("mythicshot-mark-small.svg"), true),
    "/** The tab icon: 16 and 32 pixels from the small mark, 48 from the standard one (scripts/build-icons.ts). */",
    `export const FAVICON_ICO = lazy(${JSON.stringify(brandFile("favicon.ico").toString("base64"))});`,
  ];
  for (const scheme of ["dark", "light"] as const) {
    const png = brandFile(`wordmark-${scheme}.png`);
    const id = `WORDMARK_${scheme.toUpperCase()}`;
    lines.push(
      `/** The wordmark for ${scheme} grounds (wordmark-${scheme}.png, scripts/build-wordmark.py), drawn at three times its size. */`,
      `export const ${id}_PNG = lazy(${JSON.stringify(png.toString("base64"))});`,
    );
  }
  const [width, height] = pngSize(brandFile("wordmark-light.png"));
  if (width % 3 !== 0 || height % 3 !== 0 || pngSize(brandFile("wordmark-dark.png")).join() !== [width, height].join()) throw new Error("the wordmark's pictures are not one size, three times a whole size");
  lines.push(
    "/** The size the pages show the wordmark at, in CSS pixels: a third of the pictures'. */",
    `export const WORDMARK_WIDTH = ${width / 3};`,
    `export const WORDMARK_HEIGHT = ${height / 3};`,
  );
  for (const f of FONTS) {
    const bytes = brandFile(f.file);
    const hash = digest(bytes);
    lines.push(
      "",
      `/** ${f.file.split("/").pop()}, unchanged, as served. Copy the bytes for each answer. */`,
      `export const ${f.id}_TTF = lazy(${JSON.stringify(bytes.toString("base64"))});`,
      constant(`${f.id}_ETAG`, `"${hash.slice(0, 32)}"`),
      constant(`${f.id}_PATH`, `/fonts/${f.name}.${hash.slice(0, 16)}.ttf`),
      `/** The font's licence, ${f.licence}, whole. */`,
      constant(`${f.id}_LICENCE`, textFile(f.licence), true),
    );
  }
  lines.push("");
  return lines.join("\n");
}
